// Generate client/js/game/stat-registry.js from this target's native data-generator registries report.
import {readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
const root=new URL('..',import.meta.url).pathname,version='1.18.2';
const report=join(root,'cache/port-'+version+'/generated/reports/registries.json');
const r=JSON.parse(await readFile(report,'utf8'));
const order=k=>Object.entries(r[k].entries).sort((a,b)=>a[1].protocol_id-b[1].protocol_id).map(([n])=>n.replace(/^minecraft:/,''));
const statTypes=order('minecraft:stat_type'),custom=order('minecraft:custom_stat');
const source=`// Native ${version} stat_type and custom_stat registry order, generated by tools/generate-stat-registry.mjs
// from the pinned data-generator registries report. Do not edit by hand.
export const STAT_REGISTRY_VERSION=${JSON.stringify(version)};
export const STAT_TYPES=${JSON.stringify(statTypes)};
export const CUSTOM_STATS=${JSON.stringify(custom)};
`;
const out=join(root,'client/js/game/stat-registry.js');
if(process.argv.includes('--check')){if(await readFile(out,'utf8')!==source)throw Error('Stale stat registry; run tools/generate-stat-registry.mjs');}
else await writeFile(out,source);
console.log('Native '+version+' stats: '+statTypes.length+' types, '+custom.length+' custom stats');
