// Builds the 26.3 tool block tags from the client jar. Tool rules in the native item reports
// name tags such as #minecraft:mineable/pickaxe; the old 1.20.6 default-tag table cannot be
// used because both the tag contents and the numeric block ids moved. Only the tag families
// the item tool rules consult are emitted, with nested tags fully expanded to block names.
import {spawnSync} from 'node:child_process';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const jar=join(root,'cache/port-26.3/client.jar');
const output=join(root,'client/js/game/block-tags-26.3.js');
const check=process.argv.includes('--check');

const roots=[
  'mineable/axe','mineable/hoe','mineable/pickaxe','mineable/shovel',
  'incorrect_for_copper_tool','incorrect_for_diamond_tool','incorrect_for_gold_tool',
  'incorrect_for_iron_tool','incorrect_for_netherite_tool','incorrect_for_stone_tool',
  'incorrect_for_wooden_tool','sword_efficient','sword_instantly_mines',
  'shears_extreme_breaking_speed','shears_major_breaking_speed','shears_minor_breaking_speed'
];

function jarText(path){
  const result=spawnSync('unzip',['-p',jar,path],{cwd:root,encoding:'utf8',maxBuffer:16*1024*1024});
  if(result.status!==0)throw Error('unzip failed for '+path+': '+result.stderr);
  return result.stdout;
}

export async function buildBlockTags(){
  const list=spawnSync('unzip',['-Z1',jar],{cwd:root,encoding:'utf8',maxBuffer:16*1024*1024});
  if(list.status!==0)throw Error('unzip listing failed: '+list.stderr);
  const files=list.stdout.split(/\r?\n/).filter(path=>path.startsWith('data/minecraft/tags/block/')&&path.endsWith('.json'));
  assert.equal(files.length,300,'the 26.3 client jar carries 300 block tag files');

  const tags=new Map();
  for(const path of files){
    const name='minecraft:'+path.slice('data/minecraft/tags/block/'.length,-'.json'.length);
    tags.set(name,JSON.parse(jarText(path)).values||[]);
  }
  const resolved=new Map();
  function expand(name,seen=new Set()){
    if(resolved.has(name))return resolved.get(name);
    assert.ok(tags.has(name),'tag exists: '+name);
    assert.ok(!seen.has(name),'block tag cycle at '+name);
    const next=new Set(seen).add(name);
    const out=new Set();
    for(const entry of tags.get(name)){
      const value=typeof entry==='string'?entry:entry.id;
      if(!value)continue;
      if(value.startsWith('#')){
        for(const block of expand(value.slice(1),next))out.add(block);
      }else{
        out.add(value.replace(/^minecraft:/,''));
      }
    }
    resolved.set(name,out);
    return out;
  }

  const table={};
  for(const name of roots){
    const values=[...expand('minecraft:'+name)].sort();
    table['minecraft:'+name]=values;
  }
  assert.ok(table['minecraft:mineable/pickaxe'].includes('stone'),'pickaxe tag carries stone');
  assert.ok(table['minecraft:mineable/shovel'].includes('dirt'),'shovel tag carries dirt');
  assert.ok(table['minecraft:sword_instantly_mines'].includes('bamboo'),'sword instantly-mines bamboo');
  assert.ok(table['minecraft:sword_efficient'].includes('oak_leaves'),'sword tag carries leaves through the nested leaves tag');
  assert.ok(table['minecraft:incorrect_for_wooden_tool'].includes('diamond_ore'),'wooden tool tag rejects diamond ore');
  assert.ok(!table['minecraft:incorrect_for_diamond_tool'].includes('stone'),'diamond tool accepts stone');

  const body='// Generated by tools/port-26.3/build-block-tags.mjs from the native 26.3 block tags.\n'+
    '// Do not edit by hand: run `npm run block-tags:26.3`.\n'+
    'export const NATIVE_BLOCK_TAGS_26_3=Object.freeze('+JSON.stringify({minecraftVersion:'26.3',tags:table})+');\n';
  if(check)assert.equal(await readFile(output,'utf8'),body,'client/js/game/block-tags-26.3.js is regenerated from the native jar tags');
  else await writeFile(output,body);
  console.log('Native 26.3 block tags: '+roots.length+' tool tags resolved to block names');
  return table;
}

if(process.argv[1]&&process.argv[1].endsWith('build-block-tags.mjs'))await buildBlockTags();
