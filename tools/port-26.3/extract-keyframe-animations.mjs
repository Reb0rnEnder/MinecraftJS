// Extracts AnimationDefinition constants from the pinned 26.3 client bytecode.
//
// CFR renders each constant as one Java expression:
//   AnimationDefinition.Builder.withLength(0.8333f).looping()
//     .addAnimation("body", new AnimationChannel(Targets.ROTATION,
//       new Keyframe(0f, (Vector3fc)KeyframeAnimations.degreeVec(10, 15, 0), Interpolations.CATMULLROM), ...))
//     .build();
// KeyframeAnimations already defines the wire-independent conversion: degrees to radians,
// position Y negated, scale minus one. The generated module stores exactly those engine values.
import {execFileSync} from 'node:child_process';
import {mkdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const jar = join(root, 'cache', 'port-26.3', 'client.jar');
const cfr = join(root, 'cache', 'tools', 'cfr.jar');
const outDir = join(root, 'cache', 'port-26.3', 'animation-src');
const target = join(root, 'client', 'js', 'render', 'animations-26.3.js');

// Only the 26.3-only model families whose clips the renderer consumes. Existing families keep
// their 1.19.4 clips until their own conversion is scheduled.
const CLASSES = {
  BreezeAnimation: 'breeze',
  CopperGolemAnimation: 'copper_golem',
  CreakingAnimation: 'creaking',
  NautilusAnimation: 'nautilus',
};

const name = className => 'net/minecraft/client/animation/definitions/' + className;
rmSync(outDir, {recursive: true, force: true});
mkdirSync(outDir, {recursive: true});
execFileSync('java', ['-jar', cfr, jar, ...Object.keys(CLASSES).map(name), '--outputdir', outDir], {stdio: 'ignore'});

const num = text => Number.parseFloat(text);
const vector = (kind, body) => {
  const values = body.split(',').map(part => num(part.trim()));
  if (values.length !== 3 || values.some(value => !Number.isFinite(value))) throw Error('bad vector ' + body);
  if (kind === 'degreeVec') return values.map(value => value * Math.PI / 180);
  if (kind === 'posVec') return [values[0], -values[1], values[2]];
  if (kind === 'scaleVec') return values.map(value => value - 1);
  throw Error('unknown vector kind ' + kind);
};

function channel(text) {
  const target = /AnimationChannel\.Targets\.(\w+)/.exec(text)?.[1];
  if (!target) throw Error('animation channel without target');
  const frames = [...text.matchAll(/new Keyframe\(\s*(-?[\d.]+)f,\s*\(Vector3fc\)KeyframeAnimations\.(degreeVec|posVec|scaleVec)\(([^)]*)\),\s*AnimationChannel\.Interpolations\.(\w+)\)/g)]
    .map(match => [num(match[1]), vector(match[2], match[3]), match[4].toLowerCase()]);
  return {target: target.toLowerCase(), frames};
}

// Balance parentheses so nested keyframe/channel calls cannot truncate the capture.
function addAnimations(body) {
  const found = [];
  for (let at = body.indexOf('.addAnimation('); at >= 0; at = body.indexOf('.addAnimation(', at + 1)) {
    let depth = 0, i = at + '.addAnimation'.length;
    for (; i < body.length; i++) {
      if (body[i] === '(') depth++;
      else if (body[i] === ')' && --depth === 0) break;
    }
    const call = body.slice(at + '.addAnimation('.length, i);
    const bone = /^"([^"]+)"/.exec(call)?.[1];
    if (!bone) throw Error('addAnimation without bone');
    found.push([bone, channel(call.slice(call.indexOf('new AnimationChannel')))]);
  }
  return found;
}

const output = {};
for (const [className, model] of Object.entries(CLASSES)) {
  const source = readFileSync(join(outDir, name(className) + '.java'), 'utf8');
  const clips = {};
  const re = /public static final AnimationDefinition (\w+) = AnimationDefinition\.Builder\.withLength\(([\d.]+)f\)(\.looping\(\))?(.*?)\.build\(\);/gs;
  for (const match of source.matchAll(re)) {
    const bones = {};
    for (const [bone, data] of addAnimations(match[4])) (bones[bone] ??= []).push(data);
    clips[match[1]] = {looping: !!match[3], length: num(match[2]), bones};
  }
  if (!Object.keys(clips).length) throw Error('no animations parsed for ' + className);
  output[model] = clips;
}

const body = '// Generated by tools/port-26.3/extract-keyframe-animations.mjs from the pinned client.jar.\n'
  + '// Radians, native position sign and scale deltas are already applied.\n'
  + 'export const NATIVE_ANIMATIONS_26_3=' + JSON.stringify(output) + ';\n';
writeFileSync(target, body);
console.log('Keyframe animations: ' + Object.entries(output).map(([model, clips]) => model + ' ' + Object.keys(clips).length).join(', '));
