// Builds the 26.3 item default-component table from the native item-component reports.
// These are the components every stack starts with before its patch is applied, so the
// client can show native durability, stack sizes, names, food and modifiers without
// falling back to the 766 item table. Values are kept in the report's component shape;
// the runtime normalizes the few fields whose network/report shape differs (see
// itemComponentValues26_3).
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const cache=join(root,'cache/port-26.3');
const reports=join(cache,'generated/reports/minecraft/components/item');
const registryPath=join(cache,'generated/reports/registries.json');
const output=join(root,'client/js/net/item-defaults-26.3.js');
const check=process.argv.includes('--check');

function cleanAttribute(modifier){
  return {
    type:modifier.type,
    id:modifier.id,
    amount:modifier.amount,
    operation:modifier.operation,
    slot:modifier.slot
  };
}

function normalizeDefaults(components){
  const out={};
  for(const [key,value] of Object.entries(components||{})){
    const name=key.replace(/^minecraft:/,'');
    if(name==='attribute_modifiers'){
      out[name]=Array.isArray(value)?{modifiers:value.map(cleanAttribute)}:value;
    }else if(name==='enchantments'||name==='stored_enchantments'){
      // The report serializes an empty map; consumers expect the network shape (a list).
      out[name]=value&&Object.keys(value).length?value:[];
    }else if(name==='food'){
      out[name]={...value,canAlwaysEat:value.can_always_eat??value.canAlwaysEat??false};
    }else{
      out[name]=value;
    }
  }
  return out;
}

export async function buildItemDefaults(){
  const items=JSON.parse(await readFile(join(root,'client/data/items.json'),'utf8'));
  const registries=JSON.parse(await readFile(registryPath,'utf8'));
  const attributeNames=Object.entries(registries['minecraft:attribute'].entries)
    .sort((a,b)=>a[1].protocol_id-b[1].protocol_id)
    .map(([name])=>name);
  assert.ok(attributeNames.length>0,'attribute registry entries are indexed by protocol id');
  assert.equal(attributeNames[3],'minecraft:attack_damage','native attribute id 3 is attack damage');

  const defaults=new Array(items.length);
  for(const file of (await readdir(reports)).sort()){
    const name=file.replace(/\.json$/,'');
    const item=items.find(entry=>entry.name===name);
    assert.ok(item,'native item exists for report '+name);
    const components=JSON.parse(await readFile(join(reports,file),'utf8')).components;
    defaults[item.id]={name,defaults:normalizeDefaults(components)};
  }
  assert.equal(defaults.length,1658,'the native component reports cover every 26.3 item');
  assert.ok(defaults.every(Boolean),'every native item id has a default component report');
  assert.equal(defaults[items.find(item=>item.name==='diamond_sword').id].defaults.max_damage,1561,'diamond sword durability');
  assert.deepEqual(defaults[items.find(item=>item.name==='apple').id].defaults.food,{nutrition:4,saturation:2.4,canAlwaysEat:false},'apple food defaults');
  assert.equal(defaults[items.find(item=>item.name==='stone').id].defaults.max_stack_size,64,'stone stack size');

  const body='// Generated by tools/port-26.3/build-item-defaults.mjs from the native 26.3 item-component reports.\n'+
    '// Do not edit by hand: run `npm run item-defaults:26.3`.\n'+
    'export const ITEM_DEFAULTS_26_3=Object.freeze('+JSON.stringify({minecraftVersion:'26.3',attributeNames,items:defaults})+');\n';
  if(check)assert.equal(await readFile(output,'utf8'),body,'client/js/net/item-defaults-26.3.js is regenerated from the native reports');
  else await writeFile(output,body);
  console.log('Native 26.3 item defaults: '+defaults.length+' items, '+attributeNames.length+' attributes');
  return defaults;
}

if(process.argv[1]&&process.argv[1].endsWith('build-item-defaults.mjs'))await buildItemDefaults();
