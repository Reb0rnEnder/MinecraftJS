// Builds the 26.3 blocks that require the correct tool for drops, using a small Java oracle
// that bootstraps the native registry and asks each default block state. Items.canHarvest
// uses this set with the native tool rules, replacing the absent 1.20.6 harvestTools table.
import {spawnSync} from 'node:child_process';
import {readdir,readFile,writeFile,mkdir} from 'node:fs/promises';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const cache=join(root,'cache/port-26.3');
const classes=join(cache,'generated/block-tool-classes');
const output=join(root,'client/js/game/block-tools-26.3.js');
const check=process.argv.includes('--check');

async function jars(dir){
  const out=[];
  for(const entry of await readdir(dir,{withFileTypes:true})){
    const path=join(dir,entry.name);
    if(entry.isDirectory())out.push(...await jars(path));
    else if(entry.name.endsWith('.jar'))out.push(path);
  }
  return out;
}

export async function buildBlockTools(){
  const libraryJars=await jars(join(cache,'libraries'));
  assert.ok(libraryJars.length>20,'the 26.3 libraries are extracted');
  const sep=process.platform==='win32'?';':':';
  const classpath=[join(cache,'client.jar'),...libraryJars].join(sep);
  await mkdir(classes,{recursive:true});
  const compile=spawnSync('javac',['-Xlint:none','-cp',classpath,'-d',classes,join(root,'tools/port-26.3/DumpBlockTools26_3.java')],{encoding:'utf8'});
  if(compile.status!==0)throw Error('javac failed\n'+compile.stdout+compile.stderr);
  const run=spawnSync('java',['-Djava.awt.headless=true','-cp',classes+sep+classpath,'DumpBlockTools26_3'],{encoding:'utf8',maxBuffer:16*1024*1024});
  if(run.status!==0)throw Error('block-tool dumper failed\n'+run.stdout+run.stderr);
  const names=JSON.parse(run.stdout);
  assert.ok(names.length>100,'native tool-required blocks were dumped');
  assert.ok(names.includes('minecraft:stone'),'stone requires a tool');
  assert.ok(names.includes('minecraft:iron_ore'),'iron ore requires a tool');
  assert.ok(!names.includes('minecraft:dirt'),'dirt does not require a tool');
  assert.ok(!names.includes('minecraft:glass'),'glass does not require a tool');

  const body='// Generated by tools/port-26.3/build-block-tools.mjs from the native 26.3 block registry.\n'+
    '// Do not edit by hand: run `npm run block-tools:26.3`.\n'+
    'export const NATIVE_REQUIRES_TOOL_26_3=Object.freeze('+JSON.stringify({minecraftVersion:'26.3',blocks:names})+');\n';
  if(check)assert.equal(await readFile(output,'utf8'),body,'client/js/game/block-tools-26.3.js is regenerated from the native block registry');
  else await writeFile(output,body);
  console.log('Native 26.3 tool-required blocks: '+names.length);
  return names;
}

if(process.argv[1]&&process.argv[1].endsWith('build-block-tools.mjs'))await buildBlockTools();
