import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { delimiter, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { nativeClasspath } from '../../lib/native-classpath.js';
import { cache, root, target, verify } from './prepare.mjs';

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const canonical = (v) => Array.isArray(v) ? v.map(canonical) : (v && typeof v === 'object' ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, canonical(v[k])])) : v);

export async function generatePresentation({ check = false } = {}) {
  const clientJar = await readFile(join(cache, 'client.jar'));
  const mappings = await readFile(join(cache, 'client.txt'));
  verify(clientJar, target.downloads.client, 'presentation client');
  verify(mappings, target.downloads.client_mappings, 'presentation mappings');

  const unsigned = join(cache, 'client-unsigned.jar');
  if (!existsSync(unsigned)) throw Error('Missing ' + unsigned);
  const cp = nativeClasspath(cache)
    .split(delimiter)
    .filter((entry) => !entry.includes('META-INF/versions') && !entry.includes('META-INF\\versions'));
  cp[0] = unsigned;

  const animJava = join(root, 'tools/port-1.21.11/ExtractPawsAnimations12111.java');
  const presJava = join(root, 'tools/port-1.21.11/ExtractPresentation12111.java');
  // Reuse ExtractPawsAnimations pattern for BatAnimation, or read BatAnimation via ExtractPresentation12111 + BatAnimation extractor
  const outJson = join(cache, 'presentation-native.json');
  const batAnimJson = join(cache, 'bat-animations-native.json');

  await mkdir(join(root, 'tools/fixtures'), { recursive: true });
  execFileSync(
    process.env.JAVA || 'java',
    ['-Xmx512M', '-cp', cp.join(delimiter), presJava, outJson, join(cache, 'client.txt'), batAnimJson],
    { stdio: 'pipe', maxBuffer: 16 * 1024 * 1024 }
  );

  const raw = canonical(JSON.parse(await readFile(outJson, 'utf8')));
  const oracleSha256 = sha256(await readFile(presJava));
  const fixture = {
    version: target.minecraftVersion,
    clientJarSha1: target.downloads.client.sha1,
    oracleSha256,
    batFlagsId: raw.batFlagsId,
    batPoses: raw.batPoses,
    shields: raw.shields
  };
  const fixturePath = join(root, 'tools/fixtures/presentation-1.21.11.json');
  const animModule = `// Native ${target.minecraftVersion} bat keyframes; generated by presentation-fixtures.mjs.\nexport const BAT_ANIMATIONS_774=${JSON.stringify(raw.animations)};\n`;
  const animPath = join(root, 'client/js/render/animations-bat-1.21.11.js');

  if (check) {
    const existingFix = JSON.parse(await readFile(fixturePath, 'utf8'));
    if (JSON.stringify(existingFix) !== JSON.stringify(fixture)) {
      throw Error('Stale presentation fixture ' + fixturePath);
    }
    if ((await readFile(animPath, 'utf8')) !== animModule) {
      throw Error('Stale bat animations module ' + animPath);
    }
  } else {
    await writeFile(fixturePath, JSON.stringify(fixture, null, 2) + '\n');
    await writeFile(animPath, animModule);
  }
  console.log(`Presentation 1.21.11: ${fixture.batPoses.length} bat poses, ${fixture.shields.length} shield poses`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await generatePresentation({ check: process.argv.includes('--check') });
}
