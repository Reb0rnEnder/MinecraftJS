import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { delimiter, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { nativeClasspath } from '../../lib/native-classpath.js';
import { cache, root, target, verify } from './prepare.mjs';

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const canonical = (v) => Array.isArray(v) ? v.map(canonical) : (v && typeof v === 'object' ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, canonical(v[k])])) : v);

export async function generatePaws({ check = false } = {}) {
  verify(await readFile(join(cache, 'client.jar')), target.downloads.client, 'paws client');
  verify(await readFile(join(cache, 'client.txt')), target.downloads.client_mappings, 'paws mappings');
  const unsigned = join(cache, 'client-unsigned.jar');
  if (!existsSync(unsigned)) throw Error('Missing ' + unsigned);
  const cp = nativeClasspath(cache)
    .split(delimiter)
    .filter((entry) => !entry.includes('META-INF/versions') && !entry.includes('META-INF\\versions'));
  cp[0] = unsigned;

  const animJava = join(root, 'tools/port-1.21.11/ExtractPawsAnimations12111.java');
  const jawsJava = join(root, 'tools/port-1.21.11/ExtractPaws12111.java');
  const animOut = join(cache, 'paws-anim-native.json');
  const pawsOut = join(cache, 'paws-native.json');

  execFileSync(process.env.JAVA || 'java', ['-Xmx512M', '-cp', cp.join(delimiter), animJava, animOut, join(cache, 'client.txt')], { stdio: 'pipe', maxBuffer: 8 * 1024 * 1024 });
  execFileSync(process.env.JAVA || 'java', ['-Xmx512M', '-cp', cp.join(delimiter), jawsJava, pawsOut, join(cache, 'client.txt')], { stdio: 'pipe', maxBuffer: 16 * 1024 * 1024 });

  const anim = canonical(JSON.parse(await readFile(animOut, 'utf8')));
  const raw = canonical(JSON.parse(await readFile(pawsOut, 'utf8')));
  if (Array.isArray(raw.variants)) {
    raw.variants.sort((a, b) => a.key.localeCompare(b.key) || Number(a.tame) - Number(b.tame) || Number(a.angry) - Number(b.angry));
  }
  const entityReg = JSON.parse(await readFile(join(root, 'client/data/entities.json'), 'utf8'));
  const entities = entityReg.map((e) => e.name);

  const data = {
    armadilloAgeable: raw.armadilloAgeable,
    armadilloDimensions: raw.armadilloDimensions,
    crackThresholds: raw.crackThresholds,
    dyes: raw.dyes,
    metadata: raw.metadata,
    states: raw.states,
    wolfAgeable: raw.wolfAgeable
  };
  const dataSrc = `// Native ${target.minecraftVersion} entity accessors and Armadillo state timing. Generated by paws-fixtures.mjs.\nexport const PAWS_DATA_774=${JSON.stringify(data)};\n`;
  const animSrc = `// Native Armadillo keyframes extracted from the pinned ${target.minecraftVersion} jar.\nexport const PAWS_ANIMATIONS_774=${JSON.stringify(anim)};\n`;
  const fixture = {
    version: target.minecraftVersion,
    clientJarSha1: target.downloads.client.sha1,
    extractorSha256: sha256(await readFile(jawsJava)),
    entities,
    ...raw
  };

  const dataPath = join(root, 'client/js/game/paws-data-1.21.11.js');
  const animPath = join(root, 'client/js/render/animations-paws-1.21.11.js');
  const fixPath = join(root, 'tools/fixtures/paws-1.21.11.json');
  await mkdir(join(root, 'tools/fixtures'), { recursive: true });

  if (check) {
    if ((await readFile(dataPath, 'utf8')) !== dataSrc) throw Error('Stale ' + dataPath);
    if ((await readFile(animPath, 'utf8')) !== animSrc) throw Error('Stale ' + animPath);
    if (JSON.stringify(JSON.parse(await readFile(fixPath, 'utf8'))) !== JSON.stringify(fixture)) throw Error('Stale ' + fixPath);
  } else {
    await writeFile(dataPath, dataSrc);
    await writeFile(animPath, animSrc);
    await writeFile(fixPath, JSON.stringify(fixture, null, 2) + '\n');
  }
  console.log(`Paws 1.21.11: ${raw.variants.length} wolf variant textures, ${raw.armadilloPoses.length} armadillo poses, ${raw.wolfPoses.length} wolf poses, ${raw.tails.length} tails`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await generatePaws({ check: process.argv.includes('--check') });
}
