// Regenerate client/js/game/entity-metadata-1.21.11.js and entity-registry-1.21.11.js
// from the pinned 1.21.11 client jar.
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { delimiter, join } from 'node:path';
import { nativeClasspath } from '../../lib/native-classpath.js';
import { ZipFile } from '../../lib/zip.js';
import { root, cache, target, verify } from './prepare.mjs';

verify(await readFile(join(cache, 'client.jar')), target.downloads.client, 'metadata jar');
verify(await readFile(join(cache, 'client.txt')), target.downloads.client_mappings, 'metadata mappings');

const unsignedPath = join(cache, 'client-unsigned.jar');
if (!existsSync(unsignedPath)) throw Error('Missing ' + unsignedPath);
const jar = new ZipFile(join(cache, 'client.jar'));
const unsigned = new ZipFile(unsignedPath);
for (const n of jar.list('').filter((n) => n.endsWith('.class'))) {
  if (!jar.read(n).equals(unsigned.read(n))) throw Error('Modified native class ' + n);
}

const dir = join(cache, 'metadata-audit');
const out = join(dir, 'native.json');
await mkdir(dir, { recursive: true });

const cp = nativeClasspath(cache)
  .split(delimiter)
  .filter((entry) => !entry.includes(join('bundler', 'META-INF', 'versions')));
cp[0] = unsignedPath;

const source = join(root, 'tools', 'port-1.21.11', 'ExtractMetadata12111.java');
try {
  execFileSync(process.env.JAVA || 'java', ['-Xmx512M', '-cp', cp.join(delimiter), source, out, join(cache, 'client.txt')], {
    stdio: 'pipe',
    maxBuffer: 8 * 1024 * 1024
  });
} catch (e) {
  process.stderr.write(e.stdout || '');
  process.stderr.write(e.stderr || e.message);
  throw Error('Native 1.21.11 metadata oracle failed');
}

const data = JSON.parse(await readFile(out, 'utf8'));
const outputs = [
  [
    join(root, 'client/js/game/entity-metadata-1.21.11.js'),
    '// Native 1.21.11 EntityDataAccessor ids per entity type, generated by tools/port-1.21.11/metadata-fixtures.mjs.\n' +
      'export const NATIVE_METADATA = ' + JSON.stringify(data.metadata) + ';\n'
  ],
  [
    join(root, 'client/js/game/entity-registry-1.21.11.js'),
    '// Native 1.21.11 EntityType registry and dimensions, generated by tools/port-1.21.11/metadata-fixtures.mjs.\n' +
      'export const ENTITY_REGISTRY_12111 = ' + JSON.stringify(data.entities) + ';\n'
  ]
];

const check = process.argv.includes('--check');
for (const [file, text] of outputs) {
  if (check) {
    if (await readFile(file, 'utf8') !== text) throw Error('Stale 1.21.11 entity oracle output: ' + file);
  } else {
    await writeFile(file, text);
  }
}

console.log(
  'Native 1.21.11 metadata: ' +
    Object.keys(data.metadata).length +
    ' metadata types, ' +
    data.entities.length +
    ' registered entities'
);
