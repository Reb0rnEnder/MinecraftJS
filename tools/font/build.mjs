// Requires clang with wasm32 support and wasm-ld; normal client builds use the checked-in output.
import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync,mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
const dir=mkdtempSync(join(tmpdir(),'minecraftjs-ttf-')),root=fileURLToPath(new URL('../../',import.meta.url));
try {
 const path=join(dir,'font.wasm');
 execFileSync(process.env.CLANG||'clang',['--target=wasm32','-O2','-nostdlib','-fno-builtin',...(process.env.WASM_LD?['-fuse-ld='+process.env.WASM_LD]:[]),'-Wl,--no-entry',...['alloc','init','glyph','info'].map(n=>'-Wl,--export='+n),'-Wl,--export-memory','-Wl,--initial-memory=131072','-Wl,--max-memory=67108864',join(root,'tools/font/truetype.c'),'-o',path],{stdio:'inherit'});
 const data=readFileSync(path).toString('base64');
 writeFileSync(join(root,'client/js/lib/truetype-wasm.js'),'// Generated by tools/font/build.mjs; stb_truetype (MIT/public domain), see tools/font/README.md.\nexport const TRUETYPE_WASM = '+JSON.stringify(data)+';\n');
}finally{rmSync(dir,{recursive:true,force:true});}
